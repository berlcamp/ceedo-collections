#!/usr/bin/env node
/**
 * Bundles supabase/migrations into ONE SQL file for a hosted project that is migrated by
 * hand: the shared, production Asenso project, where `supabase db push` is not used.
 *
 *   node scripts/bundle-migrations.mjs                 # every migration (first install)
 *   node scripts/bundle-migrations.mjs --after 20260923000046   # only newer ones
 *   node scripts/bundle-migrations.mjs --after A --through B   # A < version <= B (hold later ones back)
 *
 * Writes dist-sql/ceedo-<first>-<last>.sql (gitignored). Run it with psql
 * (`psql "$DB_URL" -v ON_ERROR_STOP=1 -f <file>`) or paste it into the SQL Editor.
 *
 * WHY THIS SHAPE:
 * - One transaction. A failure anywhere rolls everything back; the project is left exactly
 *   as it was. There is no half-installed state to clean up.
 * - A guard first. The bundle records what it applied in ceedo_collections.deployed_migrations
 *   and refuses to run unless the project is at exactly the version it was built against:
 *   running the first-install bundle twice, or skipping a bundle, stops before changing
 *   anything.
 * - Its own history table, NOT supabase_migrations.schema_migrations. That table belongs to
 *   the project; if Asenso itself is ever migrated with the CLI, rows from this repo in it
 *   would make its `db push` refuse ("remote versions not found locally").
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const dir = join(root, "supabase", "migrations");
const afterIndex = process.argv.indexOf("--after");
const after = afterIndex > -1 ? process.argv[afterIndex + 1] : null;
const throughIndex = process.argv.indexOf("--through");
const through = throughIndex > -1 ? process.argv[throughIndex + 1] : null;

const all = readdirSync(dir)
  .filter((f) => /^\d{14}_.+\.sql$/.test(f))
  .sort();
const files = all.filter(
  (f) => (!after || f.slice(0, 14) > after) && (!through || f.slice(0, 14) <= through),
);
if (files.length === 0) {
  console.error(after ? `Nothing after ${after}.` : "No migrations found.");
  process.exit(1);
}

const version = (f) => f.slice(0, 14);
const first = version(files[0]);
const last = version(files[files.length - 1]);

const guard = after
  ? `do $guard$
begin
  if to_regclass('ceedo_collections.deployed_migrations') is null then
    raise exception 'CEEDO is not installed here. Apply the first-install bundle first.';
  end if;
  if (select max(version) from ceedo_collections.deployed_migrations) is distinct from '${after}' then
    raise exception 'This bundle applies after ${after}, but the project is at %. Nothing was changed.',
      (select max(version) from ceedo_collections.deployed_migrations);
  end if;
end
$guard$;`
  : `do $guard$
begin
  if to_regnamespace('ceedo_collections') is not null then
    raise exception 'Schema ceedo_collections already exists. This first-install bundle must not run twice. Nothing was changed.';
  end if;
end
$guard$;`;

const history = `create table if not exists ceedo_collections.deployed_migrations (
  version    text primary key,
  name       text not null,
  applied_at timestamptz not null default now()
);
revoke all on ceedo_collections.deployed_migrations from anon, authenticated;`;

const parts = [
  `-- CEEDO Collections: migrations ${first} to ${last} (${files.length} files).`,
  `-- Generated by scripts/bundle-migrations.mjs. Do not edit; regenerate.`,
  `-- Runs as ONE transaction: on any error nothing is changed.`,
  ``,
  `begin;`,
  ``,
  guard,
  ``,
];

files.forEach((f, i) => {
  parts.push(`-- ===== ${f} =====`, readFileSync(join(dir, f), "utf8").trim(), "");
  // The history table needs the schema, which the very first migration creates.
  if (!after && i === 0) parts.push(history, "");
});
if (after) parts.push(history, "");

parts.push(
  `insert into ceedo_collections.deployed_migrations (version, name) values`,
  files.map((f) => `  ('${version(f)}', '${f.slice(15, -4)}')`).join(",\n") + ";",
  ``,
  `commit;`,
  ``,
);

mkdirSync(join(root, "dist-sql"), { recursive: true });
const out = join(root, "dist-sql", `ceedo-${first}-${last}.sql`);
writeFileSync(out, parts.join("\n"));
console.log(`${out}\n${files.length} migrations, ${first} to ${last}.`);
